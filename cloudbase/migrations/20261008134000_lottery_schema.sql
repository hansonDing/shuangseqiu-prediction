-- 双色球预测 · 基础表（CloudBase PostgreSQL）
--
-- 表名统一加 lottery_ 前缀：本环境的 public schema 由环境内所有业务共用，
-- 而 draws / account / bets 这类通用名很容易与其他业务撞车，加前缀是低成本隔离。
--
-- 访问模型：纯服务端访问（云托管里的 Node 服务持 API Key）。
-- 因此开启 RLS 且刻意不建任何策略 —— anon / authenticated 一律拒绝，
-- service_role（API Key 映射）具备 BYPASSRLS，不受影响。

CREATE TABLE IF NOT EXISTS lottery_draws (
  period     text PRIMARY KEY,
  draw_date  text,
  red1       smallint,
  red2       smallint,
  red3       smallint,
  red4       smallint,
  red5       smallint,
  red6       smallint,
  blue       smallint,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS lottery_prediction_runs (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period       text NOT NULL,
  weights      text NOT NULL,
  combos       text NOT NULL,
  prize_first  double precision NOT NULL,
  prize_second double precision NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS lottery_bets (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id     bigint NOT NULL,
  period     text NOT NULL,
  reds       text NOT NULL,
  blue       smallint NOT NULL,
  cost       double precision NOT NULL,
  status     text NOT NULL DEFAULT 'pending',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS lottery_settlements (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bet_id     bigint NOT NULL,
  period     text NOT NULL,
  red_hits   smallint NOT NULL,
  blue_hit   boolean NOT NULL,
  prize_tier smallint NOT NULL,
  prize      double precision NOT NULL,
  profit     double precision NOT NULL,
  settled_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS lottery_equity_snapshots (
  period         text PRIMARY KEY,
  cash           double precision NOT NULL,
  total_invested double precision NOT NULL,
  total_prize    double precision NOT NULL,
  cum_profit     double precision NOT NULL,
  roi            double precision NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS lottery_account (
  id              smallint PRIMARY KEY,
  initial_capital double precision NOT NULL,
  cash            double precision NOT NULL,
  total_invested  double precision NOT NULL,
  total_prize     double precision NOT NULL,
  updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS lottery_fund_transactions (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type          text NOT NULL,
  amount        double precision NOT NULL,
  balance_after double precision NOT NULL,
  ref_id        bigint,
  note          text,
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS lottery_operation_log (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type       text NOT NULL,
  message    text NOT NULL,
  detail     text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS lottery_bets_status_idx ON lottery_bets (status);
CREATE INDEX IF NOT EXISTS lottery_bets_period_idx ON lottery_bets (period);
CREATE INDEX IF NOT EXISTS lottery_bets_run_idx ON lottery_bets (run_id);
CREATE INDEX IF NOT EXISTS lottery_settlements_period_idx ON lottery_settlements (period);

ALTER TABLE lottery_draws             ENABLE ROW LEVEL SECURITY;
ALTER TABLE lottery_prediction_runs   ENABLE ROW LEVEL SECURITY;
ALTER TABLE lottery_bets              ENABLE ROW LEVEL SECURITY;
ALTER TABLE lottery_settlements       ENABLE ROW LEVEL SECURITY;
ALTER TABLE lottery_equity_snapshots  ENABLE ROW LEVEL SECURITY;
ALTER TABLE lottery_account           ENABLE ROW LEVEL SECURITY;
ALTER TABLE lottery_fund_transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE lottery_operation_log     ENABLE ROW LEVEL SECURITY;
